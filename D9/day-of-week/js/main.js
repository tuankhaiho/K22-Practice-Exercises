let dayNumber = 1;

switch (dayNumber) {
    case 1:
        console.log("Chủ Nhật");
        break;
    case 2:
        console.log("Thứ Hai");
        break;
    case 3:
        console.log("Thứ Ba");
        break;
    case 4:
        console.log("Thứ Tư");
        break;
    case 5:
        console.log("Thứ Năm");
        break;
    case 6:
        console.log("Thứ Sáu");
        break;
    case 7:
        console.log("Thứ Bảy");
        break;
    default:
        console.log("Không hợp lệ");
        break;
}
